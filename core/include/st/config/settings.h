#pragma once

#include "st/util/fs.h"

#include <string>
#include <vector>

/// Program configuration. All paths that were hard coded in the legacy program are
/// configurable through `ServiceTracker.json` next to the executable. A missing file
/// or missing keys fall back to the legacy defaults, so an installation without any
/// configuration behaves exactly like the old program.
namespace st::config {

struct Paths {
  /// Encrypted user/permission table.
  std::string usersFile = "Y:/CrossDept/Automation/ServiceCreatorApp/users.bin";
  /// Folder with the change requests ("Änderungswünsche").
  std::string requestsDir = "Y:/CrossDept/Automation/ServiceCreatorApp/REQUESTS";
  /// Root folder with one sub folder per device project ("0601 ...").
  std::string devicesRoot = "Y:/Gerätenachweise";
  /// Folder containing configs.json.
  std::string configsDir = "Y:/CrossDept/Automation/ServiceCreatorApp/configs";
  /// Shared folder with Sync.json, History.json, style.txt and temp/.
  std::string syncDir = "Y:/CrossDept/Automation/ServiceCreatorApp/SYNC";
  /// Local working copy for external services (relative to the working directory).
  std::string externLocalDir = "extern";
  /// List of the external services.
  std::string externFile = "Y:/CrossDept/Automation/ServiceCreatorApp/SYNC/extern.json";
  /// Orders ("Bestellungen").
  std::string ordersFile = "Y:/CrossDept/Automation/ServiceCreatorApp/SYNC/Bestellungen_test.json";
  /// Crash logs are copied here.
  std::string crashDir = "Y:/CrossDept/Automation/ServiceCreatorApp/crashes";

  util::fs::path syncFile() const { return util::pathFromUtf8(syncDir) / "Sync.json"; }
  util::fs::path historyFile() const { return util::pathFromUtf8(syncDir) / "History.json"; }
  util::fs::path styleFile() const { return util::pathFromUtf8(syncDir) / "style.txt"; }
  util::fs::path syncTempDir() const { return util::pathFromUtf8(syncDir) / "temp"; }
  util::fs::path oldHistoryDir() const { return util::pathFromUtf8(syncDir) / "oldhistory"; }
  util::fs::path configsFile() const { return util::pathFromUtf8(configsDir) / "configs.json"; }

  bool operator==(const Paths &) const = default;
};

struct Settings {
  Paths paths;
  /// GitHub API URL of the latest release (cpp_app updater).
  std::string updateUrl = "https://api.github.com/repos/BigAgg/ServiceCreator_Releases/releases/latest";
  std::string updateInstaller = "install_ServiceTracker.exe";
  /// This user is always a power user, even if the user table is empty or broken.
  std::string bootstrapAdmin = "ajahraus";
  /// How often shared files are checked for changes of other users.
  int refreshIntervalMs = 1000;
  /// Checklist changes are saved automatically after this idle time (0 = off).
  int autosaveDelayMs = 2000;
  /// Customers offered in the order dialog.
  std::vector<std::string> knownCustomers = {"BMG USA", "BMG UK", "BMG France", "BMG Japan", "BMG Australien"};
  /// Title of the service record (HTML).
  std::string recordTitle = "BMG Labtech GmbH Service Record";
  std::string recordFooter = "Generated by Service Tracker | BMG Labtech GmbH | This document is confidential";

  bool operator==(const Settings &) const = default;
};

/// Loads the settings. A missing file is not an error (defaults are returned).
util::Result<Settings> loadSettings(const util::fs::path &file);

/// Writes all settings (used to create a template file for administrators).
util::Status saveSettings(const util::fs::path &file, const Settings &settings);

} // namespace st::config
