#pragma once

#include "st/checklist/model.h"

#include <string>
#include <string_view>
#include <vector>

/// Read access and exports (HTML service record, CSV) of a checklist.
namespace st::checklist {

/// Formats a number with German separators: 1234.5 / "%.2f€" -> "1.234,50€".
/// Only the precision and the suffix of `fmt` are evaluated (like the legacy program).
std::string formatNumber(double value, std::string_view fmt);

/// Formats an integer with German thousands separators: 1234567 -> "1.234.567".
std::string formatInteger(long long value);

/// Value as shown in reports: bool as ✅/❌, numbers in German notation.
std::string displayValue(const Task &task);

/// Plain value without formatting: bool "1"/"0", numbers as entered, combo = selection.
std::string plainValue(const Value &value);

/// Value of the task `taskName` in `sectionName`. Table columns are joined with '\n'.
std::string retrieveValue(const Checklist &checklist, std::string_view sectionName, std::string_view taskName);

/// Sum of a numeric table column.
double tableColumnTotal(const Checklist &checklist, std::string_view sectionName, std::string_view tableName, std::string_view columnName);

struct HtmlOptions {
  /// File name shown in the header.
  std::string documentName;
  std::string appVersion;
  std::string title = "BMG Labtech GmbH Service Record";
  std::string footer = "Generated by Service Tracker | BMG Labtech GmbH | This document is confidential";
  /// Optional replacement for the complete document head (content of style.txt).
  /// Must contain everything up to and including the opening <body> and header.
  std::string customHead;
  /// Export all sections instead of finished ones only.
  bool includeUnfinished = false;
  /// Leave out working times and user names (record for customers).
  bool hideWorkInfo = false;
  /// Page header (document name, title) and footer (footer text, "Page x of y") on
  /// every printed page. Rendered by Chromium based browsers (PDF export).
  bool pageHeaderFooter = false;
};

/// Service record as a stand-alone HTML page (printable, A4).
std::string exportHtml(const Checklist &checklist, const HtmlOptions &options);

/// CSV export (';' separated, UTF-8 with BOM so Excel shows umlauts correctly).
std::string exportCsv(const Checklist &checklist, std::string_view documentPath);

/// Copy of the checklist that contains only `sectionNames` in the given order,
/// all marked as finished (used for "Record erstellen").
Checklist recordSubset(const Checklist &checklist, const std::vector<std::string> &sectionNames);

/// Finished sections that may appear in the e-mail export (Section::emailExport), in
/// checklist order (used for "E-Mail erstellen").
Checklist emailSubset(const Checklist &checklist);

/// CSS string literal (quotes included) for `content:` properties.
std::string cssString(std::string_view text);

} // namespace st::checklist
